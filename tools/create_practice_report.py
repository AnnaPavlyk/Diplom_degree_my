def p(text='', align=None, bold=False, size=None, before=0, after=6, first=1.25):
    par = doc.add_paragraph(); par.paragraph_format.space_before = Pt(before); par.paragraph_format.space_after = Pt(after); par.paragraph_format.first_line_indent = Cm(first) if first else Cm(0); par.paragraph_format.line_spacing = 1.5
    if align: par.alignment = align
    r = par.add_run(text); r.bold = bold; r.font.name = 'Times New Roman'; r._element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman'); r.font.size = Pt(size or 14)
    return par
