-- Скрипт додає відсутні значення для випадаючих списків форми «Викладач».
-- Таблиці-довідники недоступні для запису ролі «лаборант» за RLS, тому їх
-- коректно наповнювати адміністратором, а не з клієнтського застосунку.

-- Структура звірена з поточною БД: поле назви тут саме «Назва»,
-- а коди посад — 1…7. Не змінюємо наявні коди, бо на них посилається
-- «Кафедральна_інформація_про_виклад».
insert into public."Посада" ("Код_посади", "Назва") values
  ('1', 'Професор'),
  ('2', 'Доцент'),
  ('3', 'Старший викладач'),
  ('4', 'Асистент'),
  ('5', 'Старший лаборант'),
  ('6', 'Лаборант'),
  ('7', 'Завідувач кафедри')
on conflict ("Код_посади") do update
set "Назва" = excluded."Назва";

insert into public."Тип_викладача" ("Код_типу", "Назва_типу") values
  ('1', 'Штатний'),
  ('2', 'Внутрішній сумісник'),
  ('3', 'Зовнішній сумісник')
on conflict ("Код_типу") do update
set "Назва_типу" = excluded."Назва_типу";

-- НПП/ПП і річні норми вже є у вашій БД, але ці команди відновлять їх,
-- якщо запис було видалено. Код статусу використовується у кафедральній
-- інформації, а «Години × Частка_ставки» відображаються на платформі.
insert into public."Статус_викладача" ("Код_статусу_викладача", "Назва_статусу_викладача") values
  ('НПП', 'Науково-педагогічний працівник'),
  ('ПП', 'Педагогічний працівник')
on conflict ("Код_статусу_викладача") do update
set "Назва_статусу_викладача" = excluded."Назва_статусу_викладача";

insert into public."Навантаження" ("Код_статусу_викладача", "Години") values
  ('НПП', 480),
  ('ПП', 900)
on conflict ("Код_статусу_викладача") do update
set "Години" = excluded."Години";

-- Перевірка після виконання:
select
  p."Код_посади", p."Назва",
  t."Код_типу", t."Назва_типу"
from public."Посада" p
cross join public."Тип_викладача" t
order by p."Назва", t."Назва_типу";
